function RootShell({ children }: { children: ReactNode }) {
  return (
    <html lang="es" className="dark">
      <head>
        <HeadContent />
      </head>
      <body>
        {children}
        <Scripts />
      </body>
    </html>
  );
}

function RootComponent() {
  const { queryClient } = Route.useRouteContext();
  const router = useRouter();

  useEffect(() => {
    const {
      data: { subscription },
    } = supabase.auth.onAuthStateChange((event) => {
      if (event !== "SIGNED_IN" && event !== "SIGNED_OUT" && event !== "USER_UPDATED") return;
      // Si el login ocurre fuera de /auth (p. ej. retorno OAuth en "/"), retoma el destino pendiente.
      if (event === "SIGNED_IN" && router.state.location.pathname !== "/auth") {
        const pending = consumePendingAuthRedirect();
        if (pending) router.history.push(pending);
      }
      router.invalidate();
      if (event === "SIGNED_OUT") {
        queryClient.invalidateQueries({ queryKey: ["session"] });
        queryClient.invalidateQueries({ queryKey: ["roles"] });
      } else {
        queryClient.invalidateQueries();
      }
    });
    return () => subscription.unsubscribe();
  }, [router, queryClient]);

  return (
    <QueryClientProvider client={queryClient}>
      <CartProvider>
        {/* Required: nested routes render here. Removing <Outlet /> breaks all child routes. */}
        <Outlet />
        <Toaster theme="dark" richColors position="top-center" closeButton />
      </CartProvider>
    </QueryClientProvider>
  );
}
